/**
 * Шаблоны документов для страницы «Документы».
 * Поля описывают форму, build() собирает текст. Пустое поле даёт прочерк для заполнения от руки.
 */

export type Values = Record<string, string>

export interface TField {
  id: string
  label: string
  type?: 'text' | 'textarea' | 'date' | 'select'
  placeholder?: string
  options?: string[]
  default?: string
  /** 'today' подставит сегодняшнюю дату */
  defaultToday?: boolean
}

export interface Template {
  id: string
  group: string
  title: string
  summary: string
  note?: string
  articleIds?: string[]
  fields: TField[]
  build: (v: Values) => string
}

const BLANK = '________________'
const b = (v: Values, id: string, blank = BLANK) => (v[id] && v[id].trim() ? v[id].trim() : blank)
const lines = (...rows: (string | false | null | undefined)[]) => rows.filter((r) => r !== false && r != null).join('\n')
const dmy = (iso: string | undefined) => {
  if (!iso) return '«__» ________ 20__ г.'
  const d = new Date(iso)
  return Number.isNaN(d.getTime()) ? iso : d.toLocaleDateString('ru-RU')
}
const dateLine = (v: Values) => (v.date ? `${dmy(v.date)} г.` : '«__» ________ 20__ г.')

